UiBidiClass uiBidiClassOf(u32 cp) {
    u8 v = 0;
    if (bidiTable().find(cp, v)) return static_cast<UiBidiClass>(v);
    return UiBidiClass::L;
}

u32 uiMirror(u32 cp) {
    const auto& t = mirrorTable();
    const auto it = std::lower_bound(t.begin(), t.end(), std::make_pair(cp, 0u));
    return (it != t.end() && it->first == cp) ? it->second : cp;
}

UiScript uiScriptOf(u32 cp) {
    u8 v = 0;
    if (scriptTable().find(cp, v)) return static_cast<UiScript>(v);
    return UiScript::Common;   // unlisted: punctuation, digits, symbols and scripts the table does not name
}

UiLb uiLineBreakClassOf(u32 cp) {
    u8 v = 0;
    if (lineBreakTable().find(cp, v)) return static_cast<UiLb>(v);
    return UiLb::AL;
}

bool uiIsCombining(u32 cp) {
    u8 v = 0;
    return combiningTable().find(cp, v);
}

bool uiIsFormatChar(u32 cp) {
    u8 v = 0;
    return formatTable().find(cp, v);
}

bool uiUnicodeTablesSound() {
    return bidiTable().sound() && scriptTable().sound() && lineBreakTable().sound() &&
           combiningTable().sound() && formatTable().sound();
}

