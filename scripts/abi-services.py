#!/usr/bin/env python3
# The engine's seams as extension services (docs/EXTENSIONS.md, "Services"): each seam's exported functions, in a fixed
# order, at a version. The lock (scripts/abi-services.lock) is the record; the C++ table of names the engine resolves at
# run time (modules/extensions/src/SeamServices.gen.cpp) is generated from it. Stdlib only.
#
#   python scripts/abi-services.py --check                      # fail when the headers and the lock disagree (ctest AbiServicesCheck)
#   python scripts/abi-services.py --update                     # append new functions; add new seams at version 1
#   python scripts/abi-services.py --update --bump aver.nav     # a changed or removed signature: re-record that service at version + 1
#
# A table only grows at the end within a version, so code built against it keeps working. A signature that changes, a
# function that goes, or a new order is a new version: an extension that asked for the old one is refused, never handed
# slots that now mean something else. Design: docs/plans/EXTENSION_SERVICES.md.
#
# Exits 1 on any problem.

import argparse
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "scripts", "abi-services.lock")
GEN = os.path.join(ROOT, "modules", "extensions", "src", "SeamServices.gen.cpp")
LOCK_MARK = "# Generated by scripts/abi-services.py --update. Edit only through it; see docs/plans/EXTENSION_SERVICES.md."
GEN_MARK = "// Generated by scripts/abi-services.py --update from scripts/abi-services.lock. Do not edit."

_spec = importlib.util.spec_from_file_location("abi_index", os.path.join(ROOT, "scripts", "abi-index.py"))
abi = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(abi)


def service_name(seam):
    # "Aver.Render.PBR" -> "aver.render.pbr"
    return seam.lower()


def from_headers():
    """{service: {"dlls": [...], "fns": [(name, signature)] in header order}}, and the parse problems."""
    paths = abi.find_headers()
    macros = abi.export_macros(paths)
    out, problems = {}, []
    for p in paths:
        h = abi.parse_header(p, macros)
        for ln, why, text in h.skips:
            problems.append("%s:%d: %s: %s" % (h.rel, ln, why, text))
        fns = [e for e in h.entries if e.kind == "function"]
        if not fns:
            continue
        svc = service_name(abi.seam_of(h.module))
        s = out.setdefault(svc, {"dlls": [], "fns": []})
        for t in abi.module_targets(h.module):
            if t not in s["dlls"]:
                s["dlls"].append(t)
        for e in fns:
            s["fns"].append((e.name, "%s %s(%s)" % (e.ret, e.name, e.params)))
    return {k: v for k, v in out.items() if v["dlls"]}, problems


def read_lock():
    lock = {}
    if not os.path.exists(LOCK):
        return lock
    cur = None
    for raw in abi.read(LOCK).split("\n"):
        line = raw.rstrip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("service "):
            _, name, version, dlls = line.split(" ", 3)
            cur = lock[name] = {"version": int(version), "dlls": dlls.split(","), "fns": []}
        elif line.startswith("  ") and cur is not None:
            sig = line.strip()
            cur["fns"].append((sig.split("(", 1)[0].split()[-1], sig))
    return lock


def write_lock(lock):
    lines = [LOCK_MARK, "# service <name> <version> <dll[,dll]>, then its functions in table order (slot 0 first).", ""]
    for name in sorted(lock):
        s = lock[name]
        lines.append("service %s %d %s" % (name, s["version"], ",".join(s["dlls"])))
        lines += ["  " + sig for _, sig in s["fns"]]
        lines.append("")
    with open(LOCK, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def gen_text(lock):
    out = [GEN_MARK, "// One entry per service: its name, version, the DLLs that export it and its functions in table order.",
           '#include "SeamServices.hpp"', "", "namespace aver::ext::detail {", ""]
    for name in sorted(lock):
        ident = "k_" + name.replace(".", "_").replace("-", "_")
        out.append("static const char* const %s[] = {" % ident)
        out += ['    "%s",' % fn for fn, _ in lock[name]["fns"]]
        out.append("};")
    out.append("")
    out.append("const SeamServiceSpec kSeamServices[] = {")
    for name in sorted(lock):
        s = lock[name]
        ident = "k_" + name.replace(".", "_").replace("-", "_")
        out.append('    {"%s", %d, "%s", %s, %d},' % (name, s["version"], ";".join(s["dlls"]), ident, len(s["fns"])))
    out.append("};")
    out.append("const usize kSeamServiceCount = sizeof(kSeamServices) / sizeof(kSeamServices[0]);")
    out += ["", "}  // namespace aver::ext::detail", ""]
    return "\n".join(out)


def compare(lock, heads):
    """(appendable {svc: [(name, sig)]}, needs_bump {svc: [why]}, new services [svc], gone services [svc])."""
    append, bump, new, gone = {}, {}, [], []
    for svc, h in heads.items():
        if svc not in lock:
            new.append(svc)
            continue
        hsig = dict(h["fns"])
        locked = dict(lock[svc]["fns"])
        why = []
        for name, sig in lock[svc]["fns"]:
            if name not in hsig:
                why.append("%s was removed" % name)
            elif hsig[name] != sig:
                why.append("%s changed: %s -> %s" % (name, sig, hsig[name]))
        if why:
            bump[svc] = why
        extra = [(n, s) for n, s in h["fns"] if n not in locked]
        if extra:
            append[svc] = extra
    for svc in lock:
        if svc not in heads:
            gone.append(svc)
    return append, bump, new, gone


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--update", action="store_true")
    ap.add_argument("--bump", action="append", default=[], metavar="SERVICE")
    a = ap.parse_args()

    heads, problems = from_headers()
    if problems:
        for p in problems:
            print("abi-services: " + p, file=sys.stderr)
        return 1
    lock = read_lock()
    append, bump, new, gone = compare(lock, heads)

    if a.check:
        bad = []
        for svc, why in sorted(bump.items()):
            bad += ["%s: %s; the slots would change meaning, so it needs a new version: --update --bump %s" % (svc, w, svc) for w in why]
        for svc, fns in sorted(append.items()):
            bad += ["%s: %s is not in the lock: --update appends it" % (svc, n) for n, _ in fns]
        bad += ["%s: a new seam, not in the lock: --update adds it at version 1" % s for s in sorted(new)]
        bad += ["%s: in the lock but no header exports it any more: --update --bump %s" % (s, s) for s in sorted(gone)]
        cur = abi.read(GEN) if os.path.exists(GEN) else ""
        if cur.replace("\r\n", "\n") != gen_text(lock):
            bad.append("%s is stale: --update rewrites it" % abi.rel(GEN))
        for b in bad:
            print("abi-services: " + b, file=sys.stderr)
        if bad:
            return 1
        print("abi services ok: %d services, %d functions" % (len(lock), sum(len(s["fns"]) for s in lock.values())))
        return 0

    unknown = [b for b in a.bump if b not in lock]
    if unknown:
        print("abi-services: --bump names a service the lock does not have: " + ", ".join(unknown), file=sys.stderr)
        return 1
    refused = [s for s in sorted(set(bump) | set(gone)) if s not in a.bump]
    if refused:
        for s in refused:
            for w in bump.get(s, ["no header exports it any more"]):
                print("abi-services: %s: %s" % (s, w), file=sys.stderr)
            print("abi-services: %s needs a new version: --update --bump %s" % (s, s), file=sys.stderr)
        return 1
    for s in a.bump:
        if s in gone:
            del lock[s]
            print("removed %s" % s)
            continue
        lock[s] = {"version": lock[s]["version"] + 1, "dlls": heads[s]["dlls"], "fns": list(heads[s]["fns"])}
        print("%s -> version %d (%d functions, re-recorded in header order)" % (s, lock[s]["version"], len(lock[s]["fns"])))
    for s, fns in sorted(append.items()):
        if s in a.bump:
            continue
        lock[s]["fns"] += fns
        lock[s]["dlls"] = heads[s]["dlls"]
        print("%s: appended %d function(s)" % (s, len(fns)))
    for s in sorted(new):
        lock[s] = {"version": 1, "dlls": heads[s]["dlls"], "fns": list(heads[s]["fns"])}
        print("%s: added at version 1 (%d functions)" % (s, len(lock[s]["fns"])))
    write_lock(lock)
    with open(GEN, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_text(lock))
    print("wrote %s and %s" % (abi.rel(LOCK), abi.rel(GEN)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
