#!/usr/bin/env python3
# Generates the register assignments, the kernel wrappers and the C++ register table of the hair compute host
# (docs/plans/wave11/SOFTBODY_HAIR.md 2.11, docs/HAIR.md).
#
#   python scripts/gen-hair-shader-regs.py            # write the outputs
#   python scripts/gen-hair-shader-regs.py --check    # exit 1 when an output differs from what Jolt's headers imply
#
# WHY IT EXISTS. Jolt's fifteen hair kernels declare their buffers as bare `StructuredBuffer<T> name;` with no register, and let each of its own
# compute backends discover the register by reflection. Aver's RHI binds a compute shader's buffers as CONTIGUOUS slot ranges (t0.. for read-only,
# u0.. for read-write) and its constants at b3 / b4, so the registers must be explicit. The vendored kernels are compiled UNCHANGED: a wrapper per
# kernel (shaders/AverJolt<Name>.hlsl) defines JPH_SHADER_OVERRIDE_MACROS, includes AverHairMacros.hlsli (the macro block of Jolt's
# Shaders/ShaderCore.h with `: register(AVER_REG_<name>)` added) and the generated AverJolt<Name>.regs.hlsli, then includes the vendored file.
#
# THE RULE, which is what DXC would assign anyway: within a kernel, read-only bindings are t0, t1, ... and read-write bindings u0, u1, ... in
# the order Jolt's <Name>Bindings.h declares them; gContext is b3 and gIterationContext is b4 in every kernel (the RHI declares both slots in
# every hair pipeline layout, and the host binds both before each dispatch). The wind kernel (modules/physics/shaders/hair/AverHairWind.hlsl)
# has its own cbuffer, gWind, at b3.
#
# OUTPUTS (checked in; run by hand when Jolt is updated, and re-derived by tests/render.hair/HairRegsTest):
#   modules/render.hair/shaders/AverJolt<Name>.regs.hlsli   one `#define AVER_REG_<binding> <reg>` per binding, plus b3 / b4
#   modules/render.hair/shaders/AverJolt<Name>.hlsl         the wrapper
#   modules/render.hair/shaders/AverHairWindCS.hlsl (+ .regs.hlsli)
#   modules/render.hair/src/HairRegs.inc                    {kernel, wrapper file, binding table} rows for RhiComputeHost.cpp
import argparse
import os
import re
import sys

KERNELS = [
    "HairTeleport", "HairApplyDeltaTransform", "HairSkinVertices", "HairSkinRoots", "HairApplyGlobalPose",
    "HairCalculateCollisionPlanes", "HairGridClear", "HairGridAccumulate", "HairGridNormalize", "HairIntegrate",
    "HairUpdateRoots", "HairUpdateStrands", "HairUpdateVelocity", "HairUpdateVelocityIntegrate", "HairCalculateRenderPositions",
]
WIND = "AverHairWind"

# Bindings.h files spell three of their bindings through overridable aliases (the CPU wrappers redefine them).
ALIASES = {
    "JPH_SHADER_BIND_SCALP_VERTICES": ("JPH_float3", False),
    "JPH_SHADER_BIND_SCALP_TRIANGLES": ("JPH_uint", False),
    "JPH_SHADER_BIND_RENDER_POSITIONS": ("JPH_float3", True),
}
BUF_RE = re.compile(r"JPH_SHADER_BIND_(RW_)?BUFFER\(\s*(\w+)\s*,\s*(\w+)\s*\)")
ALIAS_RE = re.compile(r"(JPH_SHADER_BIND_\w+)\(\s*(\w+)\s*\)")


def repo_root():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def parse_bindings(text):
    """Returns [(name, type, rw)] for the bindings between JPH_SHADER_BIND_BEGIN and _END, in declaration order."""
    out = []
    inside = False
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("#") or line.startswith("//"):
            continue
        if "JPH_SHADER_BIND_BEGIN" in line:
            inside = True
            continue
        if "JPH_SHADER_BIND_END" in line:
            inside = False
            continue
        if not inside:
            continue
        m = BUF_RE.search(line)
        if m:
            out.append((m.group(3), m.group(2), m.group(1) is not None))
            continue
        m = ALIAS_RE.search(line)
        if m and m.group(1) in ALIASES:
            ty, rw = ALIASES[m.group(1)]
            out.append((m.group(2), ty, rw))
    return out


def assign(bindings):
    t = u = 0
    rows = []
    for name, ty, rw in bindings:
        if rw:
            rows.append((name, ty, True, u))
            u += 1
        else:
            rows.append((name, ty, False, t))
            t += 1
    return rows, t, u


def regs_text(stem, source_note, rows, wind):
    lines = [
        "// GENERATED by scripts/gen-hair-shader-regs.py from %s -- do not edit." % source_note,
        "// Registers of the %s kernel: read-only bindings are t0.., read-write u0.. in declaration order; constants are b3 / b4." % stem,
    ]
    if wind:
        lines.append("#define AVER_REG_gWind b3")
    else:
        lines.append("#define AVER_REG_gContext b3")
        lines.append("#define AVER_REG_gIterationContext b4")
    for name, ty, rw, slot in rows:
        lines.append("#define AVER_REG_%s %s%d" % (name, "u" if rw else "t", slot))
    return "\n".join(lines) + "\n"


def wrapper_text(stem, vendored, regs_file, jolt_note):
    return (
        "// GENERATED by scripts/gen-hair-shader-regs.py -- do not edit.\n"
        "// Aver.Render.Hair: %s compiled UNCHANGED. The macro override gives every binding an explicit register; the vendored kernel\n"
        "// (deployed beside this file, %s) is not touched. %s\n"
        "#define JPH_SHADER_OVERRIDE_MACROS\n"
        "#include \"AverHairMacros.hlsli\"\n"
        "#include \"%s\"\n"
        "#include \"%s\"\n"
    ) % (stem, vendored, jolt_note, regs_file, vendored)


def wind_wrapper_text(regs_file):
    return (
        "// GENERATED by scripts/gen-hair-shader-regs.py -- do not edit.\n"
        "// Aver.Render.Hair: the wind kernel (modules/physics/shaders/hair/AverHairWind.hlsl, deployed beside this file) as HLSL. It declares its own\n"
        "// constants (gWind at b3) and reads only the velocity struct, so the struct header it includes is the small AverHairWindStructs.hlsli\n"
        "// instead of Jolt's HairStructs.h (which would declare gContext at b3 as well).\n"
        "#define JPH_SHADER_OVERRIDE_MACROS\n"
        "#define AVER_HAIR_STRUCTS_INCLUDE \"AverHairWindStructs.hlsli\"\n"
        "#include \"AverHairMacros.hlsli\"\n"
        "#include \"%s\"\n"
        "#include \"AverHairWind.hlsl\"\n"
    ) % regs_file


def inc_text(kernels):
    out = ["// GENERATED by scripts/gen-hair-shader-regs.py -- do not edit. Included inside a namespace by RhiComputeHost.cpp and HairRegsTest.cpp,",
           "// after HairRegsTypes.hpp. One row per compute kernel; a binding's `kind` is 0 for a read-only (t) slot and 1 for a read-write (u) slot.", ""]
    for name, wrapper, rows, t, u in kernels:
        out.append("inline constexpr HairKernelBinding kBindings_%s[] = {" % name)
        for bname, ty, rw, slot in rows:
            out.append('    {"%s", %d, %d},' % (bname, 1 if rw else 0, slot))
        out.append("};")
    out.append("")
    out.append("inline constexpr HairKernel kHairKernels[] = {")
    for name, wrapper, rows, t, u in kernels:
        out.append('    {"%s", "%s", %d, %d, %d, kBindings_%s},' % (name, wrapper, t, u, len(rows), name))
    out.append("};")
    out.append("inline constexpr unsigned kHairKernelCount = %d;" % len(kernels))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    root = repo_root()
    jolt = os.path.join(root, "modules", "physics.jolt", "Jolt", "Shaders")
    wind_src = os.path.join(root, "modules", "physics", "shaders", "hair", "AverHairWind.hlsl")
    out_dir = os.path.join(root, "modules", "render.hair", "shaders")
    inc_path = os.path.join(root, "modules", "render.hair", "src", "HairRegs.inc")

    files = {}
    kernels = []
    for name in KERNELS:
        with open(os.path.join(jolt, name + "Bindings.h"), encoding="utf-8") as f:
            rows, t, u = assign(parse_bindings(f.read()))
        if not rows:
            print("no bindings parsed for", name, file=sys.stderr)
            return 1
        stem = "AverJolt" + name
        files[stem + ".regs.hlsli"] = regs_text(stem, "Jolt/Shaders/%sBindings.h" % name, rows, False)
        files[stem + ".hlsl"] = wrapper_text(stem, name + ".hlsl", stem + ".regs.hlsli", "Constants: gContext b3, gIterationContext b4.")
        kernels.append((name, stem + ".hlsl", rows, t, u))

    with open(wind_src, encoding="utf-8") as f:
        wrows, wt, wu = assign(parse_bindings(f.read()))
    if not wrows:
        print("no bindings parsed for the wind kernel", file=sys.stderr)
        return 1
    files["AverHairWindCS.regs.hlsli"] = regs_text("AverHairWind", "modules/physics/shaders/hair/AverHairWind.hlsl", wrows, True)
    files["AverHairWindCS.hlsl"] = wind_wrapper_text("AverHairWindCS.regs.hlsli")
    kernels.append((WIND, "AverHairWindCS.hlsl", wrows, wt, wu))

    contents = {os.path.join(out_dir, k): v for k, v in files.items()}
    contents[inc_path] = inc_text(kernels)

    bad = 0
    for path, text in sorted(contents.items()):
        cur = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                cur = f.read().replace("\r\n", "\n")
        if cur == text:
            continue
        if args.check:
            print("differs:", os.path.relpath(path, root))
            bad += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, root))
    if args.check and bad:
        print("run: python scripts/gen-hair-shader-regs.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
