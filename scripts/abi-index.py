#!/usr/bin/env python3
# The native C ABI, indexed from source: one page per seam under docs/abi/, every exported function as a table row
# with its return type, parameters, the first sentence of the comment above it and header:line. Stdlib only.
#
#   python scripts/abi-index.py --write     # regenerate docs/abi/*.md
#   python scripts/abi-index.py --check     # fail when a page is missing or stale, or a declaration was skipped (ctest AbiIndexCheck)
#   python scripts/abi-index.py --counts    # export count per header and per seam
#
# It reads every modules/**/include/**/*_abi.h (plus framework_hooks.h, a function-pointer table). A declaration is a
# statement that starts with the header's export macro (any `#define X ... dllexport` macro); the section it sits in is
# the last `---- Title ----` banner comment above it. Function-pointer typedefs are listed as callback types and are not
# counted as exports. A declaration shape it does not understand is skipped and reported, never guessed at.
# Guide: docs/ABI.md.
#
# Exits 1 on any problem.

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = os.path.join(ROOT, "modules")
DOCS_ABI = os.path.join(ROOT, "docs", "abi")
MARK = "<!-- Generated by scripts/abi-index.py --write. Do not edit; see docs/ABI.md. -->"
EXTRA_HEADERS = ["framework_hooks.h"]
SEAMS = {"scene": "Aver.Scene", "framework": "Aver.Framework", "physics": "Aver.Physics", "render.pbr": "Aver.Render.PBR",
         "render.voxi": "Aver.Render.Voxi", "scripting": "Aver.Scripting", "ui.abi": "Aver.UI", "audio.abi": "Aver.Audio",
         "settings": "Aver.Settings", "anim.abi": "Aver.Anim", "nav.abi": "Aver.Nav", "net.abi": "Aver.Net",
         "prefab": "Aver.Prefab", "levelinstance.abi": "Aver.LevelInstance", "synapse.abi": "Aver.Synapse"}


def read(path):
    with open(path, encoding="utf-8", newline=None) as f:
        return f.read()


def rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


# ---------------------------------------------------------------------------------------------------------------
# comments and code

def lex(text):
    """(code, comments). `code` is `text` with comments blanked (newlines kept, so offsets and lines agree); `comments`
    is [(start_line, end_line, own_line, lines, kind)] with 1-based lines and the comment's text lines, markers stripped."""
    out, comments = [], []
    i, n, line = 0, len(text), 1
    line_has_code = False
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = text.find("\n", i)
            j = n if j < 0 else j
            comments.append((line, line, not line_has_code, [text[i + 2:j].strip()], "line"))
            out.append(" " * (j - i))
            i = j
            continue
        if c == "/" and nxt == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            body = text[i + 2:max(i + 2, j - 2)]
            lines = [re.sub(r"^\s*\*+\s?", "", l).strip() if k else l.strip() for k, l in enumerate(body.split("\n"))]
            nl = text.count("\n", i, j)
            comments.append((line, line + nl, not line_has_code, lines, "block"))
            out.append(re.sub(r"[^\n]", " ", text[i:j]))
            line += nl
            i = j
            continue
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
            line_has_code = True
            continue
        out.append(c)
        if c == "\n":
            line += 1
            line_has_code = False
        elif not c.isspace():
            line_has_code = True
        i += 1
    return "".join(out), comments


def blank_preprocessor(code):
    """The code with preprocessor lines (and their continuations) blanked."""
    lines = code.split("\n")
    k = 0
    while k < len(lines):
        if lines[k].lstrip().startswith("#"):
            while True:
                cont = lines[k].rstrip().endswith("\\")
                lines[k] = " " * len(lines[k])
                k += 1
                if not cont or k >= len(lines):
                    break
        else:
            k += 1
    return "\n".join(lines)


BANNER = re.compile(r"^[-=]{3,}\s*(.*?)\s*[-=]*\s*$")


def group_comments(comments):
    """Merge consecutive own-line // comments into one block. Returns [(start, end, own_line, lines)]."""
    out = []
    for c in sorted(comments):
        if out and c[2] and out[-1][2] and c[0] == out[-1][1] + 1 and out[-1][4] == "line" and c[4] == "line":
            p = out[-1]
            out[-1] = (p[0], c[1], True, p[3] + c[3], "line")
        else:
            out.append(c)
    return out


def banner_title(lines):
    """The section title when the comment block opens with a ---- Title ---- line, else None."""
    if not lines:
        return None
    m = BANNER.match(lines[0])
    if not m:
        return None
    title = m.group(1)
    if not title:                                   # a bare rule: the title is the next line
        for l in lines[1:]:
            if l and not re.match(r"^[-=]+$", l):
                title = re.sub(r"\s*[-=]{3,}\s*$", "", l).strip()
                break
    return title or None


def first_sentence(lines):
    para = []
    for l in lines:
        if not l:
            if para:
                break
            continue
        para.append(l)
    txt = " ".join(para)
    txt = " ".join(txt.split())
    if not txt:
        return ""
    m = re.match(r"(.+?(?<!e\.g)(?<!i\.e)(?<!etc)(?<!vs)[.!?])(?=\s+[A-Z(`\"]|\s*$)", txt)
    s = (m.group(1) if m else txt).strip()
    if len(s) > 220:
        s = s[:217].rstrip() + "..."
    return s


# ---------------------------------------------------------------------------------------------------------------
# a header

class Entry:
    def __init__(self, kind, name, ret, params, line, summary, section):
        self.kind, self.name, self.ret, self.params = kind, name, ret, params
        self.line, self.summary, self.section = line, summary, section


class Header:
    def __init__(self, path):
        self.path = path
        self.rel = rel(path)
        self.base = os.path.basename(path)
        self.module = rel(path).split("/")[1]
        self.macros = []        # export macros the declarations use
        self.versions = []      # (name, text)
        self.entries = []
        self.skips = []         # (line, why, text)


def norm(s):
    return " ".join(s.split())


def norm_ret(s):
    s = norm(s)
    s = re.sub(r"\s*\*", "*", s)
    return s.replace("*", "*").strip()


def statements(code):
    """[(start_offset, text)] of top-level statements of the preprocessor-blanked code, `extern "C" {` removed."""
    code = re.sub(r'extern\s+"C"\s*\{', lambda m: " " * len(m.group(0)), code)
    out, depth, start = [], 0, None
    for i, c in enumerate(code):
        if start is None and not c.isspace():
            start = i
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth < 0:
                depth = 0
        elif c == ";" and depth == 0 and start is not None:
            out.append((start, code[start:i]))
            start = None
    if start is not None and code[start:].strip():
        out.append((start, code[start:]))
    return out


def eval_define(expr, defs):
    e = re.sub(r"\b([A-Za-z_]\w*)\b", lambda m: str(defs[m.group(1)]) if m.group(1) in defs and isinstance(defs[m.group(1)], int) else m.group(0), expr)
    if re.fullmatch(r"[0-9xXa-fA-F\s()<>|+\-&]*", e) and e.strip():
        try:
            return int(eval(e, {"__builtins__": {}}, {}))
        except Exception:
            return None
    return None


def parse_header(path, export_macros):
    h = Header(path)
    raw = read(path)
    code, comments = lex(raw)
    blocks = group_comments(comments)
    # versions: #define NAME value, NAME containing VERSION
    defs = {}
    for m in re.finditer(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)[ \t]+([^\n]*?)[ \t]*(?:\\)?$", code, re.M):
        v = m.group(2).strip()
        if re.fullmatch(r"-?(0[xX][0-9a-fA-F]+|\d+)", v):
            defs[m.group(1)] = int(v, 0)
    for m in re.finditer(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*VERSION\w*)[ \t]+(.*)$", code, re.M):
        name, expr = m.group(1), m.group(2).strip()
        if m.group(0).rstrip().endswith("\\"):
            tail = code[m.end():].split("\n")[1:2]
            expr = expr.rstrip("\\").strip() + " " + (tail[0].strip() if tail else "")
        if not expr or not name.startswith("AVER"):
            continue
        v = eval_define(expr, defs)
        if v is None:
            h.versions.append((name, expr))
        elif name.endswith(("_MAJOR", "_MINOR")) or v < 1000:
            h.versions.append((name, str(v)))
        else:
            h.versions.append((name, "0x%X" % v))
    body = blank_preprocessor(code)
    lines_at = [0]
    for m in re.finditer(r"\n", body):
        lines_at.append(m.end())

    def line_of(off):
        lo, hi = 0, len(lines_at) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if lines_at[mid] <= off:
                lo = mid
            else:
                hi = mid - 1
        return lo + 1

    banners = sorted((b[0], banner_title(b[3])) for b in blocks if banner_title(b[3]))
    by_end = {}
    for b in blocks:
        if b[2]:
            by_end[b[1]] = b
    inline = {}
    for b in blocks:
        if not b[2]:
            inline[b[0]] = b

    def section_at(line):
        sec = "General"
        for ln, title in banners:
            if ln < line:
                sec = title
            else:
                break
        return sec

    def summary_at(line, end_line):
        b = by_end.get(line - 1)
        if b is not None and banner_title(b[3]) is None:
            s = first_sentence(b[3])
            if s:
                return s
        b = inline.get(end_line)
        if b is not None:
            return first_sentence(b[3])
        return ""

    macro_re = re.compile(r"^(?:%s)\b" % "|".join(sorted(export_macros, key=len, reverse=True)))
    used = set()
    for off, text in statements(body):
        ln = line_of(off)
        end_ln = line_of(off + len(text))
        t = norm(text)
        if t.startswith("typedef"):
            m = re.match(r"typedef\s+(.+?)\s*\(\s*(?:\w+\s*)?\*\s*(\w+)\s*\)\s*\((.*)\)$", t)
            if m:
                h.entries.append(Entry("callback", m.group(2), norm_ret(m.group(1)), norm(m.group(3)), ln,
                                       summary_at(ln, end_ln), section_at(ln)))
            continue
        mm = macro_re.match(t)
        if not mm:
            if re.search(r"\w\s*\([^;{}]*\)\s*$", t) and "{" not in t and not t.startswith(("struct", "enum", "union", "static_assert")):
                h.skips.append((ln, "function-like declaration without an export macro", t[:80]))
            continue
        if "{" in t:
            h.skips.append((ln, "declaration with a body", t[:80]))
            continue
        rest = t[mm.end():].strip()
        m = re.match(r"^(.*?)\b([A-Za-z_]\w*)\s*\((.*)\)$", rest)
        if not m or not m.group(1).strip():
            h.skips.append((ln, "shape not understood", t[:80]))
            continue
        used.add(mm.group(0))
        h.entries.append(Entry("function", m.group(2), norm_ret(m.group(1)), norm(m.group(3)), ln,
                               summary_at(ln, end_ln), section_at(ln)))
    h.macros = sorted(used)
    return h


def find_headers():
    out = []
    for dp, dn, fn in os.walk(MODULES):
        dn[:] = sorted(d for d in dn if d not in ("build", "third_party", "bin", "obj"))
        if os.sep + "include" + os.sep not in dp + os.sep:
            continue
        for f in sorted(fn):
            if f.endswith("_abi.h") or f in EXTRA_HEADERS:
                out.append(os.path.join(dp, f))
    return sorted(out, key=lambda p: rel(p))


def export_macros(paths):
    macros = set()
    for p in paths:
        code, _ = lex(read(p))
        for m in re.finditer(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)[ \t]+.*(?:dllexport|visibility)", code, re.M):
            macros.add(m.group(1))
    return macros


def module_targets(module):
    path = os.path.join(MODULES, module, "CMakeLists.txt")
    if not os.path.exists(path):
        return []
    code = re.sub(r"#[^\n]*", "", read(path))
    return sorted(set(re.findall(r"add_library\(\s*([\w.]+)\s+SHARED", code)))


# ---------------------------------------------------------------------------------------------------------------
# pages

def cell(s):
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def code_cell(s):
    return "`%s`" % s.replace("|", "\\|") if s else ""


def seam_of(module):
    return SEAMS.get(module) or "Aver." + "".join(p.capitalize() for p in module.replace(".abi", "").split("."))


def version_text(h):
    return ", ".join("`%s` = %s" % (n, v) for n, v in h.versions)


def short_version(h):
    d = dict(h.versions)
    maj = next((v for n, v in d.items() if n.endswith("_VERSION_MAJOR")), None)
    mnr = next((v for n, v in d.items() if n.endswith("_VERSION_MINOR")), None)
    if maj is not None and mnr is not None:
        return "%s.%s" % (maj, mnr)
    for n, v in h.versions:
        if n.endswith("_ABI_VERSION"):
            return v
    return h.versions[0][1] if h.versions else ""


def anchor(text):
    return re.sub(r"[^a-z0-9_ -]", "", text.lower()).replace(" ", "-")


def seam_page(seam, headers, targets):
    funcs = sum(1 for h in headers for e in h.entries if e.kind == "function")
    cbs = sum(1 for h in headers for e in h.entries if e.kind == "callback")
    macros = sorted({m for h in headers for m in h.macros})
    out = [MARK, "", "# %s C ABI" % seam, ""]
    dll = ", ".join("`%s`" % t for t in targets) if targets else "no DLL of its own (a header-only contract)"
    line = "DLL: %s. Export macro: %s. %d exported function%s in %d header%s" % (
        dll, ", ".join("`%s`" % m for m in macros) if macros else "none",
        funcs, "" if funcs == 1 else "s", len(headers), "" if len(headers) == 1 else "s")
    if cbs:
        line += ", %d callback type%s" % (cbs, "" if cbs == 1 else "s")
    out += [line + ". Guide: `docs/ABI.md`; all seams: [index](index.md).", ""]
    for h in headers:
        out += ["## %s" % h.base, ""]
        n = sum(1 for e in h.entries if e.kind == "function")
        meta = "`%s`" % h.rel
        if h.macros and len(macros) > 1:
            meta += ". Export macro: %s" % ", ".join("`%s`" % m for m in h.macros)
        meta += ". %d export%s" % (n, "" if n == 1 else "s")
        if h.versions:
            meta += ". Version: " + version_text(h)
        out += [meta + ".", ""]
        sections = {}
        for e in h.entries:
            sections.setdefault((e.kind == "callback", e.section), []).append(e)
        order = sorted(sections, key=lambda k: (k[0], k[1] != "General", min(e.line for e in sections[k]), k[1]))
        for key in order:
            is_cb, sec = key
            entries = sections[key]
            title = ("Callback types - " + sec) if is_cb and sec != "General" else ("Callback types" if is_cb else sec)
            out += ["### %s" % cell(title), ""]
            out += ["| %s | Returns | Parameters | Summary | Source |" % ("Type" if is_cb else "Function"), "|---|---|---|---|---|"]
            for e in sorted(entries, key=lambda e: (e.name.lower(), e.name)):
                out.append("| `%s` | %s | %s | %s | `%s:%d` |" % (
                    e.name, code_cell(e.ret), code_cell(e.params), cell(e.summary), h.rel, e.line))
            out.append("")
    return "\n".join(out)


def build():
    paths = find_headers()
    macros = export_macros(paths)
    headers = [parse_header(p, macros) for p in paths]
    seams = {}
    for h in headers:
        seams.setdefault(seam_of(h.module), []).append(h)
    pages, stats = {}, []
    for seam in sorted(seams):
        hs = sorted(seams[seam], key=lambda h: (h.base != seam_primary(seam, hs_names(seams[seam])), h.base))
        modules = sorted({h.module for h in hs})
        targets = sorted({t for m in modules for t in module_targets(m)})
        pages[seam + ".md"] = seam_page(seam, hs, targets)
        stats.append((seam, hs, targets))
    pages["index.md"] = index_page(stats)
    return pages, headers, stats


def hs_names(hs):
    return [h.base for h in hs]


def seam_primary(seam, names):
    """The seam's main header: the one named for the seam, else the shortest name."""
    stem = seam.split(".")[-1].lower()
    for n in sorted(names, key=lambda n: (len(n), n)):
        if n.startswith(stem + "_") or n.startswith(stem.replace("level", "level_") + "_"):
            return n
    return sorted(names, key=lambda n: (len(n), n))[0]


def index_page(stats):
    out = [MARK, "", "# C ABI index", "",
           "Generated from `modules/**/include/**/*_abi.h` (and `framework_hooks.h`) by `scripts/abi-index.py`. The guide is "
           "`docs/ABI.md`: type rules, handles, the error convention, versioning, how a call reaches the DLL, adding an entry point.", "",
           "## Seams", "", "| Seam | Headers | DLL | Version | Exports | Callbacks |", "|---|---|---|---|---|---|"]
    total_f = total_c = 0
    rows = []
    for seam, hs, targets in stats:
        f = sum(1 for h in hs for e in h.entries if e.kind == "function")
        c = sum(1 for h in hs for e in h.entries if e.kind == "callback")
        total_f += f
        total_c += c
        names = [h.base for h in hs]
        main = next(h for h in hs if h.base == seam_primary(seam, names))
        v = short_version(main)
        others = sum(1 for h in hs if h is not main and h.versions)
        if others:
            v = (v + " " if v else "") + "(+%d versioned sub-header%s)" % (others, "" if others == 1 else "s")
        hdr = "`%s`" % main.rel if len(hs) == 1 else "`%s` and %d more" % (main.rel, len(hs) - 1)
        out.append("| [%s](%s.md) | %s | %s | %s | %d | %d |" % (
            seam, seam, hdr, ", ".join("`%s`" % t for t in targets) if targets else "none", v or "none", f, c))
    out += ["| **Total** | %d headers | | | **%d** | **%d** |" % (sum(len(hs) for _, hs, _ in stats), total_f, total_c), ""]
    items = []
    for seam, hs, _ in stats:
        for h in hs:
            for e in h.entries:
                if e.kind == "function":
                    items.append((e.name, seam, h.base + (" / " + e.section if e.section != "General" else ""), "%s:%d" % (h.rel, e.line)))

    def key(n):
        s = n[len("aver_"):] if n.startswith("aver_") else n
        return (s.lower(), n)

    items.sort(key=lambda it: key(it[0]))

    def letter(n):
        s = n[len("aver_"):] if n.startswith("aver_") else n
        c = s[:1].upper()
        return c if c.isalpha() else "Other"

    letters = sorted({letter(it[0]) for it in items}, key=lambda l: (l == "Other", l))
    out += ["## A-Z", "", "Sorted by the name after the `aver_` prefix. " + " ".join("[%s](#%s)" % (l, l.lower()) for l in letters), ""]
    cur = None
    for name, seam, sec, src in items:
        l = letter(name)
        if l != cur:
            if cur is not None:
                out.append("")
            cur = l
            out += ["### %s" % l, "", "| Function | Seam | Section | Source |", "|---|---|---|---|"]
        out.append("| `%s` | [%s](%s.md) | %s | `%s` |" % (name, seam, seam, cell(sec), src))
    out.append("")
    return "\n".join(out)


def existing(dirpath):
    out = {}
    if os.path.isdir(dirpath):
        for f in os.listdir(dirpath):
            if f.endswith(".md"):
                out[f] = read(os.path.join(dirpath, f))
    return out


def main():
    ap = argparse.ArgumentParser(description="Index the native C ABI into docs/abi.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a page is missing or stale or a declaration was skipped")
    ap.add_argument("--write", action="store_true", help="regenerate docs/abi")
    ap.add_argument("--counts", action="store_true", help="print export counts per header and per seam")
    ap.add_argument("--out", metavar="DIR", help="write the pages here instead of docs/abi (for a trial run)")
    args = ap.parse_args()
    if not (args.check or args.write or args.counts):
        ap.print_help()
        return 0

    pages, headers, stats = build()
    skips = [(h, s) for h in headers for s in h.skips]

    if args.counts:
        for seam, hs, _ in stats:
            for h in hs:
                print("%-34s %-30s %4d exports %3d callbacks" % (seam, h.base, sum(e.kind == "function" for e in h.entries),
                                                                  sum(e.kind == "callback" for e in h.entries)))
            print("%-34s %-30s %4d" % (seam, "TOTAL", sum(e.kind == "function" for h in hs for e in h.entries)))
        print("TOTAL %d exports in %d headers, %d skipped" % (sum(e.kind == "function" for h in headers for e in h.entries), len(headers), len(skips)))
        for h, (ln, why, txt) in skips:
            print("SKIP %s:%d %s: %s" % (h.rel, ln, why, txt))
        if not (args.check or args.write):
            return 0

    if args.write:
        out = os.path.abspath(args.out) if args.out else DOCS_ABI
        os.makedirs(out, exist_ok=True)
        for name, text in pages.items():
            with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
        for name, text in existing(out).items():
            if name not in pages and text.startswith(MARK):
                os.remove(os.path.join(out, name))
                print("removed stale %s" % name)
        print("wrote %d pages to %s" % (len(pages), out))
        for h, (ln, why, txt) in skips:
            print("SKIP %s:%d %s: %s" % (h.rel, ln, why, txt))
        return 0

    have = existing(DOCS_ABI)
    problems = []
    for name, text in sorted(pages.items()):
        if name not in have:
            problems.append("docs/abi/%s is missing" % name)
        elif have[name] != text:
            problems.append("docs/abi/%s is stale" % name)
    for name, text in have.items():
        if name not in pages and text.startswith(MARK):
            problems.append("docs/abi/%s is generated but no seam produces it any more: remove it" % name)
    for h, (ln, why, txt) in skips:
        problems.append("skipped declaration %s:%d (%s): %s" % (h.rel, ln, why, txt))
    seen = {}
    for h in headers:
        for e in h.entries:
            if e.kind == "function":
                if e.name in seen:
                    problems.append("%s is declared twice: %s and %s:%d" % (e.name, seen[e.name], h.rel, e.line))
                seen.setdefault(e.name, "%s:%d" % (h.rel, e.line))
    for p in problems:
        print("FAIL: " + p)
    if problems:
        print("\n%d problem(s). Run: python scripts/abi-index.py --write" % len(problems))
        return 1
    print("ABI index ok: %d pages, %d exports" % (len(pages), sum(e.kind == "function" for h in headers for e in h.entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
