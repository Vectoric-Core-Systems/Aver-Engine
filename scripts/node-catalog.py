class Entry:
    def __init__(self):
        self.type_id = self.display = self.category = ""
        self.pins = []      # (name, type, isOutput, default text or None); None when not evaluable
        self.attrs = []     # keys
        self.domain = "gameplay"
        self.file = ""
        self.line = 0


class Cursor:
    def __init__(self, text, i):
        self.t, self.i = text, i

    def ws(self):
        while self.i < len(self.t) and self.t[self.i].isspace():
            self.i += 1


def parse_value(c):
    """A tiny C++ expression reader: strings, braced lists, calls, identifiers; anything else as raw text."""
    c.ws()
    t = c.t
    if c.i >= len(t):
        raise ValueError("unexpected end")
    ch = t[c.i]
    if ch == '"':
        j = c.i + 1
        while j < len(t) and t[j] != '"':
            j += 2 if t[j] == "\\" else 1
        lit = t[c.i:j + 1]
        c.i = j + 1
        v = ("s", unescape(lit))
        c.ws()
        while c.i < len(t) and t[c.i] == '"':      # adjacent literals concatenate
            j = c.i + 1
            while j < len(t) and t[j] != '"':
                j += 2 if t[j] == "\\" else 1
            v = ("s", v[1] + unescape(t[c.i:j + 1]))
            c.i = j + 1
            c.ws()
        return v
    if ch == "{":
        c.i += 1
        items = []
        while True:
            c.ws()
            if t[c.i] == "}":
                c.i += 1
                return ("l", items)
            items.append(parse_value(c))
            c.ws()
            if t[c.i] == ",":
                c.i += 1
            elif t[c.i] != "}":
                raise ValueError("expected , or } at offset %d" % c.i)
    m = re.compile(r"[A-Za-z_][\w:]*").match(t, c.i)
    if m:
        c.i = m.end()
        name = m.group(0)
        if c.i < len(t) and t[c.i] == "(":
            close = match_paren(t, c.i)
            if close < 0:
                raise ValueError("call not closed")
            sub = Cursor(t[:close], c.i + 1)
            args = []
            while True:
                sub.ws()
                if sub.i >= len(sub.t):
                    break
                args.append(parse_value(sub))
                sub.ws()
                if sub.i < len(sub.t) and sub.t[sub.i] == ",":
                    sub.i += 1
            c.i = close + 1
            return ("c", name, args)
        c.ws()
        if c.i < len(t) and t[c.i] == "|":           # kDomainGameplay | kDomainMaterial
            c.i += 1
            other = parse_value(c)
            return ("id", name + "|" + (other[1] if other[0] == "id" else "?"))
        return ("id", name)
    # raw: up to a top-level , } )
    depth, j = 0, c.i
    while j < len(t):
        if t[j] in "({[":
            depth += 1
        elif t[j] in ")}]":
            if depth == 0:
                break
            depth -= 1
        elif t[j] == "," and depth == 0:
            break
        j += 1
    raw = t[c.i:j].strip()
    c.i = j
    return ("raw", raw)


def eval_pins(node, env):
    """A list of (name, type, isOutput, default) for a pin expression, or None when it cannot be evaluated."""
    kind = node[0]
    if kind == "l":
        res = []
        for it in node[1]:
            if it[0] == "c" and it[1] == "pin":
                a = it[2]
                if len(a) < 3 or a[0][0] != "s" or a[1][0] != "s" or a[2][0] != "id":
                    return None
                dflt = a[3][1] if len(a) > 3 and a[3][0] == "s" else None
                res.append((a[0][1], a[1][1], a[2][1] == "true", dflt if dflt != "" else None))
            elif it[0] == "c" and it[1] == "fl" and it[2] and it[2][0][0] == "s":
                res.append((it[2][0][1], "float", False, None))
            elif it[0] == "id" and it[1] in env:
                sub = eval_pins(env[it[1]], env)
                if sub is None:
                    return None
                res += sub
            else:
                return None
        return res
    if kind == "id" and node[1] in env:
        return eval_pins(env[node[1]], env)
    if kind == "c" and node[1] == "query" and len(node[2]) == 2:
        ins, outs = eval_pins(node[2][0], env), eval_pins(node[2][1], env)
        if ins is None or outs is None:
            return None
        ins = ins + [("layerMask", "int", False, None), ("ignoreBody", "int", False, None),
                     ("includeSensors", "bool", False, None)]
        return [("exec", "exec", False, None)] + ins + [("then", "exec", True, None)] + outs
    return None


def parse_palette_file(path, problems):
    raw = read(path)
    text = strip_comments(raw, "cpp")
    env = {}
    for m in re.finditer(r"(?:const\s+)?auto\s+(\w+)\s*=\s*std::vector<GraphPinSpec>\s*\{", text):
        try:
            env[m.group(1)] = parse_value(Cursor(text, m.end() - 1))
        except (ValueError, IndexError):
            pass
    entries = []
    for m in re.finditer(r"(?<![\w.])t\.push_back\s*\(\s*\{", text):
        start = m.end() - 1
        where = "%s:%d" % (rel(path), line_of(text, start))
        try:
            v = parse_value(Cursor(text, start))
            e = make_entry(v, env)
        except (ValueError, IndexError) as ex:
            problems.append("C1 %s: cannot parse the palette entry (%s)" % (where, ex))
            continue
        e.file, e.line = rel(path), line_of(text, start)
        entries.append(e)
    return entries


def make_entry(v, env):
    if v[0] != "l" or len(v[1]) < 4:
        raise ValueError("an entry needs typeId, display name, category and pins")
    it = v[1]
    for k in range(3):
        if it[k][0] != "s":
            raise ValueError("entry field %d is not a string" % k)
    e = Entry()
    e.type_id, e.display, e.category = it[0][1], it[1][1], it[2][1]
    e.pins = eval_pins(it[3], env)
    for extra in it[4:]:
        if extra[0] == "l":
            for a in extra[1]:
                if a[0] == "c" and a[1] == "attr" and a[2] and a[2][0][0] == "s":
                    e.attrs.append(a[2][0][1])
        elif extra[0] == "id" and "kDomainMaterial" in extra[1]:
            e.domain = "material"
            if "kDomainGameplay" in extra[1]:
                e.domain = "both"
        elif extra[0] == "id" and "kDomainBoth" in extra[1]:
            e.domain = "both"
    return e


def palette_files():
    return sorted(f for f in os.listdir(SANDBOX_DIR) if re.fullmatch(r"GraphNodeDefs\w*\.hpp", f))


def parse_palette(problems):
    entries = []
    for f in palette_files():
        entries += parse_palette_file(os.path.join(SANDBOX_DIR, f), problems)
    return entries


def serves_gameplay(e):
    return e.domain in ("gameplay", "both")


