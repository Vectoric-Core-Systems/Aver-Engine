# checks

def default_equal(row_default, ptype, pal_default):
    if row_default is None and pal_default is None:
        return True
    if row_default is None or pal_default is None:
        return False
    if ptype == "bool":
        return row_default.lower() == pal_default.lower()
    try:
        return float(row_default) == float(pal_default)
    except ValueError:
        return row_default == pal_default


def fmt_pin(p):
    return "%s:%s:%s%s" % (p[0], p[1], "out" if p[2] else "in", "=" + p[3] if p[3] is not None else "")


def check(rows, calls, entries, labels, problems):
    gameplay = {}
    for e in entries:
        if serves_gameplay(e):
            gameplay.setdefault(e.type_id.lower(), []).append(e)

    # C1 (the count half): the parsed rows are every Reg( call
    if calls != len(rows):
        problems.append("C1 %d Reg( calls but %d rows parsed" % (calls, len(rows)))

    # C6: keys
    seen = {}
    for r in rows:
        k = r.key.lower()
        if k in seen:
            problems.append("C6 %s: key '%s' is also defined at %s:%d" % (r.file, r.key, seen[k].file, seen[k].line))
        seen[k] = r
        if k in labels:
            problems.append("C6 %s:%d: key '%s' is also a case label of OcGraphParser.AddDefaultPins, "
                            "which would shadow the row" % (r.file, r.line, r.key))
    pal_seen = {}
    for e in entries:
        k = (e.type_id.lower(), e.domain)
        if k in pal_seen:
            o = pal_seen[k]
            problems.append("C6 %s:%d: palette typeId '%s' is also at %s:%d" % (e.file, e.line, e.type_id, o.file, o.line))
        pal_seen[k] = e

    for r in rows:
        where = "%s:%d" % (r.file, r.line)
        pal = gameplay.get(r.key.lower())
        # C2
        if not pal:
            problems.append("C2 %s: row '%s' has no palette entry (a GraphNodeDefs*.hpp t.push_back with typeId '%s')"
                            % (where, r.key, r.key))
            continue
        e = pal[0]
        # C3
        if e.pins is None:
            problems.append("C3 %s: palette entry %s:%d has pins this script cannot read" % (where, e.file, e.line))
        else:
            want, got = r.derived_pins(), e.pins
            same = len(want) == len(got) and all(
                w[0] == g[0] and w[1] == g[1] and w[2] == g[2] and default_equal(w[3], w[1], g[3])
                for w, g in zip(want, got))
            if not same:
                problems.append("C3 %s: pins of '%s' differ from the palette at %s:%d\n      row:     %s\n      palette: %s"
                                % (where, r.key, e.file, e.line, ", ".join(fmt_pin(p) for p in want),
                                   ", ".join(fmt_pin(p) for p in got)))
        # C4
        if r.kind != "Trigger":
            toks = r.attributes()
            keys = list(e.attrs)
            unmatched = []
            for alts, _opt in toks:
                hit = next((k for k in keys if k in alts), None)
                if hit is None:
                    unmatched.append("|".join(alts))
                else:
                    keys.remove(hit)
            if unmatched or keys:
                problems.append("C4 %s: attributes of '%s' differ from the palette at %s:%d (row needs %s; palette has %s)"
                                % (where, r.key, e.file, e.line,
                                   ", ".join("|".join(a) for a, _ in toks) or "none", ", ".join(e.attrs) or "none"))
        # C7 / C9
        if r.family not in LEGACY_FAMILIES:
            if r.key != r.key.lower() or r.key != e.type_id.lower():
                problems.append("C7 %s: key '%s' must be the lower-case palette typeId '%s'" % (where, r.key, e.type_id.lower()))
            if not re.fullmatch(r"[A-Za-z0-9_]+", e.type_id):
                problems.append("C7 %s:%d: palette typeId '%s' may only use letters, digits and underscore" % (e.file, e.line, e.type_id))
            if not e.category.strip():
                problems.append("C7 %s:%d: palette entry '%s' has no category" % (e.file, e.line, e.type_id))

    # C5: a family header entry with no row must be a hand-parsed node
    rowkeys = {r.key.lower() for r in rows}
    for e in entries:
        if e.file.endswith("GraphNodeDefs.hpp") or not serves_gameplay(e):
            continue
        if e.type_id.lower() not in rowkeys and e.type_id.lower() not in labels:
            problems.append("C5 %s:%d: palette entry '%s' has no table row and the parser has no case for it"
                            % (e.file, e.line, e.type_id))

    # C9: non-legacy families have a registered test file
    prog = read(os.path.join(TESTS_DIR, "Program.cs")) if os.path.exists(os.path.join(TESTS_DIR, "Program.cs")) else ""
    for fam in sorted({r.family for r in rows} - LEGACY_FAMILIES):
        tf = os.path.join(TESTS_DIR, fam + "NodeTests.cs")
        if not os.path.exists(tf):
            problems.append("C9 family %s has no scripting/csharp/Aver.Graph.Tests/%sNodeTests.cs" % (fam, fam))
            continue
        listed = re.search(r"\b%sNodeTests\.RunAll\s*\(" % re.escape(fam), prog) is not None
        auto = re.search(r"\[AutoRun\]\s*(?:internal\s+|public\s+)?static\s+class\s+%sNodeTests\b" % re.escape(fam), read(tf)) is not None
        if not (listed or auto):
            problems.append("C9 %sNodeTests is neither marked [AutoRun] nor run from Program.cs" % fam)


