_cs_cache = None


def csharp_sources():
    global _cs_cache
    if _cs_cache is not None:
        return _cs_cache
    files = {}
    for dp, dn, fn in os.walk(CSHARP_DIR):
        dn[:] = [d for d in dn if d not in ("bin", "obj") and not d.endswith(".Tests")]
        for f in fn:
            if f.endswith(".cs"):
                p = os.path.join(dp, f)
                files[p] = read(p)
    classes = {}
    for p, t in files.items():
        for m in re.finditer(r"\bclass\s+(\w+)", t):
            classes.setdefault(m.group(1), []).append(p)
    _cs_cache = (files, classes)
    return _cs_cache


def doc_summary(owner, method):
    files, classes = csharp_sources()
    pat = re.compile(r"^[ \t]*(?:\[[^\]\n]*\]\s*)*(?:(?:public|internal|private|protected|static|unsafe|extern)\s+)+[^\n(=;]*?\b"
                     + re.escape(method) + r"\s*(?:<[^>\n]*>)?\s*\(", re.M)
    for p in classes.get(owner, []):
        t = files[p]
        m = pat.search(t)
        if not m:
            continue
        lines = t[:m.start()].split("\n")[:-1]
        doc = []
        k = len(lines) - 1
        while k >= 0 and (lines[k].strip().startswith("///") or lines[k].strip().startswith("[") or lines[k].strip() == ""):
            if lines[k].strip().startswith("///"):
                doc.insert(0, lines[k].strip()[3:])
            elif lines[k].strip() == "":
                break
            k -= 1
        blob = " ".join(doc)
        s = re.search(r"<summary>(.*?)</summary>", blob, re.S)
        if not s:
            return ""
        txt = re.sub(r"<see\s+cref=\"([^\"]+)\"\s*/>", lambda mm: mm.group(1).split(".")[-1], s.group(1))
        txt = re.sub(r"<(?:param|typeparam)ref\s+name=\"([^\"]+)\"\s*/>", r"\1", txt)
        txt = re.sub(r"</?[a-zA-Z][^>]*>", "", txt)
        txt = " ".join(html.unescape(txt).split())
        first = re.match(r"(.+?[.!?])(?:\s|$)", txt)
        return (first.group(1) if first else txt).strip()
    return ""


