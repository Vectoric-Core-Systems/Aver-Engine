def main():
    ap = argparse.ArgumentParser(description="Aver Node catalog: check, write, count, scaffold.")
    ap.add_argument("--check", action="store_true", help="exit 1 on any disagreement")
    ap.add_argument("--write", action="store_true", help="regenerate docs/nodes")
    ap.add_argument("--counts", action="store_true", help="print the counts")
    ap.add_argument("--scaffold-palette", metavar="FAMILY", help="print a GraphNodeDefs<Family>.hpp body")
    ap.add_argument("--category", default="Category", help="palette category for --scaffold-palette")
    ap.add_argument("--out", metavar="DIR", help="write the pages here instead of docs/nodes (for a trial run)")
    args = ap.parse_args()

    problems = []
    rows, calls = parse_tables(problems)
    entries = parse_palette(problems)
    labels = parser_labels()

    if args.counts:
        counts(rows, entries, labels)
        return 0
    if args.scaffold_palette:
        return scaffold(rows, args.scaffold_palette, args.category)

    check(rows, calls, entries, labels, problems)
    pages = build_pages(rows, entries)
    if args.write:
        if problems:
            print("%d problem(s); writing the pages anyway:" % len(problems))
            for p in problems:
                print("  " + p)
        write_pages(pages, os.path.abspath(args.out) if args.out else DOCS_NODES)
        return 0
    if args.check:
        check_pages(pages, problems)
    else:
        ap.print_help()
        return 0
    for p in problems:
        print("FAIL: " + p)
    if problems:
        print("\n%d problem(s). Fix the table or the palette (scripts/node-catalog.py --scaffold-palette prints a "
              "starting point), then run --write for the pages." % len(problems))
        return 1
    print("node catalog ok: %d rows, %d palette entries, %d parser labels" % (len(rows), len(entries), len(labels)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
