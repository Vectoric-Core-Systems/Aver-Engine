def counts(rows, entries, labels):
    fams = {}
    for r in rows:
        fams[r.family] = fams.get(r.family, 0) + 1
    gp = [e for e in entries if serves_gameplay(e)]
    mat = [e for e in entries if e.domain == "material"]
    rowkeys = {r.key.lower() for r in rows}
    print("table rows:        %d in %d families" % (len(rows), len(fams)))
    for f in sorted(fams):
        print("  %-18s %d" % (f, fams[f]))
    print("palette entries:   %d (%d gameplay, %d material-only) in %d files" % (
        len(entries), len(gp), len(mat), len({e.file for e in entries})))
    for f in palette_files():
        n = len([e for e in entries if e.file.endswith("/" + f)])
        print("  %-38s %d" % (f, n))
    print("palette without a table row (hand-parsed, in Core.md): %d gameplay" % len(
        [e for e in gp if e.type_id.lower() not in rowkeys]))
    print("parser vocabulary: %d distinct case labels in OcGraphParser.AddDefaultPins" % len(labels))


def pascal_words(s):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", s)


def scaffold(rows, family, category):
    mine = [r for r in rows if r.family.lower() == family.lower()]
    if not mine:
        print("no C# table rows for family '%s' (families: %s)" % (family, ", ".join(sorted({r.family for r in rows}))),
              file=sys.stderr)
        return 1
    fam = mine[0].family
    out = ["#pragma once",
           "// Palette entries for the %s nodes. NOT standalone: cmake/GraphNodeFamilies.cmake includes it from" % fam,
           "// GraphNodeDefs.hpp (namespace aver::editor::detail, after pin() and attr()) and calls append%sNodeDefs(t)." % fam,
           "// MIRRORS scripting/csharp/Aver.Graph/Graph%sNodeTable.cs pin for pin; scripts/node-catalog.py --check holds it to that." % fam,
           "",
           "inline void append%sNodeDefs(std::vector<GraphNodeDesc>& t) {" % fam]
    for r in mine:
        base = re.sub(r"ForGraph$", "", r.method or "")
        prefix = "AN_" if r.key.startswith("an_") else ""
        stem = r.key[3:] if prefix else r.key
        pascal = base if base and base.lower() == stem else (stem[:1].upper() + stem[1:])
        type_id = prefix + pascal
        display = pascal_words(pascal)
        pins = []
        for n, t, o, d in r.derived_pins():
            dflt = ', "%s"' % d if d is not None else ""
            pins.append('pin("%s", "%s", %s%s)' % (n, t, "true" if o else "false", dflt))
        attrs = ""
        keys = []
        for alts, _ in r.attributes():
            k = alts[0]
            keys.append('attr("%s", "%s")' % (k, k[:1].upper() + k[1:]))
        if keys:
            attrs = ",\n        {%s}" % ", ".join(keys)
        out.append('    t.push_back({"%s", "%s", "%s", {' % (type_id, display, category))
        line = "       "
        lines = []
        for i, p in enumerate(pins):
            piece = " " + p + ("," if i + 1 < len(pins) else "}")
            if len(line) + len(piece) > 118:
                lines.append(line)
                line = "       "
            line += piece
        lines.append(line)
        out += lines
        out[-1] += attrs + "});" if attrs else "});"
    out.append("}")
    print("\n".join(out))
    return 0


