#!/usr/bin/env python3
# The Aver Node catalog: keeps the C# node tables, the editor palette that mirrors them and the node reference
# in agreement, and writes that reference. Stdlib only.
#
#   python scripts/node-catalog.py --check      # fail on any disagreement (ctest NodeCatalogCheck)
#   python scripts/node-catalog.py --write      # regenerate docs/nodes/<Family>.md and docs/nodes/Core.md
#   python scripts/node-catalog.py --counts     # table / palette / parser counts, for a sentence in a doc
#   python scripts/node-catalog.py --scaffold-palette Family --category Cat
#                                               # print a GraphNodeDefs<Family>.hpp body from the C# rows
#
# Sources it reads (nothing is built or run):
#   scripting/csharp/Aver.Graph/Graph*NodeTable.cs   the Reg(...) rows, one table per family
#   sandbox/src/GraphNodeDefs*.hpp                   the palette (t.push_back({...}) entries), core and families
#   scripting/csharp/Aver.Graph/OcGraphParser.cs     the hand-written parser vocabulary (AddDefaultPins cases)
#   scripting/csharp/Aver.Graph.Tests/               one <Family>NodeTests.cs per family that is not a legacy one
#
# Checks (docs/plans/wave9/VISUAL_SCRIPTING_CSHARP_SYNC.md section 2.1):
#   C1 every Reg( parses            C2 every row has a palette entry (typeId equals the key, any case)
#   C3 pins equal: name, type, direction, order, default      C4 palette attribute keys equal the row's @ tokens
#   C5 a family header entry with no row is hand-parsed       C6 keys unique across tables, palette, parser labels
#   C7 naming of families that are not legacy                 C8 docs/nodes pages current
#   C9 a family that is not legacy has a test file that is registered
#
# Exits 1 on any problem.

