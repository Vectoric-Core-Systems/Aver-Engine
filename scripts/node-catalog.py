class Row:
    def __init__(self):
        self.key = self.kind = self.owner = self.method = self.ret = None
        self.ins = []      # (name, type, default text or None)
        self.outs = []     # (name, type)
        self.args = []
        self.family = ""
        self.file = ""
        self.line = 0

    def derived_pins(self):
        """(name, type, isOutput, default) in the order the parser gives a bare node."""
        if self.kind == "Trigger":
            return [("exec", "exec", True, None)]
        pins = []
        if self.kind == "Exec":
            pins.append(("exec", "exec", False, None))
        pins += [(n, t, False, d) for n, t, d in self.ins]
        if self.kind == "Exec":
            pins.append(("then", "exec", True, None))
        pins += [(n, t, True, None) for n, t in self.outs]
        return pins

    def attributes(self):
        """[(alternatives, optional)] for each @ token."""
        out = []
        for a in self.args:
            if a.startswith("@"):
                tok = a[1:]
                opt = tok.endswith("?")
                out.append((tok.rstrip("?").split("|"), opt))
        return out


def match_paren(text, i):
    """Index of the ')' matching the '(' at i, skipping string literals; -1 when unbalanced."""
    depth, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def split_top(s):
    """Splits on commas outside strings and brackets."""
    parts, depth, cur, i, n = [], 0, [], 0, len(s)
    while i < n:
        c = s[i]
        if c == '"':
            j = i + 1
            while j < n and s[j] != '"':
                j += 2 if s[j] == "\\" else 1
            cur.append(s[i:j + 1])
            i = j + 1
            continue
        if c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail or parts:
        parts.append(tail)
    return parts


def parse_pin_list(text, outputs_only=False):
    res = []
    for part in [p for p in text.split(",") if p.strip()]:
        eq = part.split("=", 1)
        nt = eq[0].split(":")
        if len(nt) != 2:
            raise ValueError("pin '%s'" % part)
        res.append((nt[0].strip(), nt[1].strip(), eq[1].strip() if len(eq) > 1 else None))
    return res


def parse_tables(problems):
    """Every Reg row of every Graph*NodeTable.cs. Returns (rows, reg_call_count)."""
    rows, calls = [], 0
    for name in sorted(os.listdir(GRAPH_DIR)):
        if not (name.startswith("Graph") and name.endswith("NodeTable.cs")):
            continue
        path = os.path.join(GRAPH_DIR, name)
        text = strip_comments(read(path), "cs")
        starts = [(m.start(), m.group(1)) for m in re.finditer(r"GenericNodeSpec\[\]\s+(\w+)\s*\(\s*\)", text)]
        if not starts:
            problems.append("C1 %s: no GenericNodeSpec[] table method found" % rel(path))
            continue
        for idx, (pos, method) in enumerate(starts):
            end = starts[idx + 1][0] if idx + 1 < len(starts) else len(text)
            family = "GameSystem" if method == "Table" else (method[:-5] if method.endswith("Table") else method)
            body = text[pos:end]
            for m in re.finditer(r"(?<![\w.])Reg\s*\(", body):
                calls += 1
                open_i = pos + m.end() - 1
                close_i = match_paren(text, open_i)
                where = "%s:%d" % (rel(path), line_of(text, open_i))
                if close_i < 0:
                    problems.append("C1 %s: Reg( is not closed" % where)
                    continue
                try:
                    rows.append(make_row(split_top(text[open_i + 1:close_i]), family, rel(path), line_of(text, open_i)))
                except ValueError as e:
                    problems.append("C1 %s: cannot parse the row (%s)" % (where, e))
    return rows, calls


def make_row(a, family, file, line):
    if len(a) != 8:
        raise ValueError("%d arguments, expected 8" % len(a))
    r = Row()
    if not a[0].startswith('"'):
        raise ValueError("key is not a string literal")
    r.key = unescape(a[0])
    m = re.fullmatch(r"GenericKind\.(Exec|Pure|Trigger)", a[1])
    if not m:
        raise ValueError("kind '%s'" % a[1])
    r.kind = m.group(1)
    m = re.fullmatch(r"typeof\(\s*([\w.]+)\s*\)", a[2])
    if not m:
        raise ValueError("owner '%s'" % a[2])
    r.owner = m.group(1).split(".")[-1]
    for i in (3, 4, 5, 6):
        if not a[i].startswith('"'):
            raise ValueError("argument %d is not a string literal" % (i + 1))
    r.method = unescape(a[3])
    r.ins = parse_pin_list(unescape(a[4]))
    r.outs = [(n, t) for n, t, _ in parse_pin_list(unescape(a[5]))]
    r.args = [x for x in unescape(a[6]).split(",") if x]
    r.ret = None if a[7] == "null" else unescape(a[7])
    for _, t, _ in r.ins:
        if t not in PIN_TYPES[:3]:
            raise ValueError("pin type '%s'" % t)
    r.family, r.file, r.line = family, file, line
    return r


