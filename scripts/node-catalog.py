# parser vocabulary

def parser_labels():
    """The distinct `case "x":` labels of OcGraphParser.AddDefaultPins."""
    text = strip_comments(read(PARSER), "cs")
    m = re.search(r"\bvoid\s+AddDefaultPins\s*\(", text)
    if not m:
        return set()
    b = text.find("{", m.end())
    depth, i = 0, b
    while i < len(text):
        if text[i] == '"':
            i += 1
            while i < len(text) and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    body = text[b:i]
    return {x for x in re.findall(r'\bcase\s+"([a-z0-9_]+)"\s*:', body)}


