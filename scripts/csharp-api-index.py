#!/usr/bin/env python3
# The public C# scripting surface, indexed from source: one page per assembly under docs/api/, every public type and
# member as a single-line signature with the first sentence of its XML summary. Stdlib only.
#
#   python scripts/csharp-api-index.py --write     # regenerate docs/api/*.md
#   python scripts/csharp-api-index.py --check     # fail when a page is missing or stale (ctest CsharpApiIndexCheck)
#
# It reads the .cs files rather than compiled XML because the XML only exists after a build and only
# Aver.Framework emits it. It is a scanner, not a compiler: nested types are listed flat with their parent's name as a
# prefix, members of a partial type are merged, and a declaration shape it does not understand is skipped, never
# guessed at. Docs: docs/SCRIPTING_API.md.
#
# Exits 1 on any problem.

import argparse
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSHARP = os.path.join(ROOT, "scripting", "csharp")
DOCS_API = os.path.join(ROOT, "docs", "api")
ASSEMBLIES = ["Aver.Framework", "Aver.Scene", "Aver.Physics", "Aver.UI", "Aver.Synapse", "Aver.LevelInstance",
              "Aver.Prefab", "Aver.Scripting", "Aver.Pcg.Apply", "Aver.Fabric"]
# An assembly that lives outside scripting/csharp (an extension's managed half): the folder that holds its project directory.
EXTERNAL_ROOTS = {"Aver.Fabric": os.path.join(ROOT, "extensions", "FabricConnector", "managed")}
MARK = "<!-- Generated by scripts/csharp-api-index.py --write. Do not edit; see docs/SCRIPTING_API.md. -->"
TYPE_DECL = re.compile(r"^(?:(?:public|internal|private|protected|static|sealed|abstract|partial|unsafe|readonly|ref|file|new)\s+)*"
                       r"(class|struct|interface|enum|record(?:\s+(?:struct|class))?)\s+([A-Za-z_]\w*)")


def read(path):
    with open(path, encoding="utf-8", newline=None) as f:
        return f.read()


def rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


# ---------------------------------------------------------------------------------------------------------------
# a code view: comments and the insides of literals blanked, newlines and offsets kept

def code_view(text, keep_strings=False):
    out = []
    i, n = 0, len(text)
    blank = lambda s: re.sub(r"[^\n]", " ", s)
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        if c == "/" and nxt == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(blank(text[i:j]))
            i = j
            continue
        if c == "#" and (i == 0 or text[i - 1] == "\n" or text[:i].rsplit("\n", 1)[-1].strip() == ""):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        if c == '"':
            if text.startswith('"""', i):                                   # raw string
                q = 3
                while text.startswith('"' * (q + 1), i):
                    q += 1
                j = text.find('"' * q, i + q)
                j = n if j < 0 else j + q
                out.append(text[i:j] if keep_strings else '"' + blank(text[i + 1:j - 1]) + '"')
                i = j
                continue
            verbatim = i > 0 and text[i - 1] == "@" or (i > 1 and text[i - 2:i] in ('@$', '$@'))
            j = i + 1
            while j < n:
                if verbatim:
                    if text[j] == '"':
                        if j + 1 < n and text[j + 1] == '"':
                            j += 2
                            continue
                        break
                    j += 1
                else:
                    if text[j] == "\\":
                        j += 2
                        continue
                    if text[j] == '"' or text[j] == "\n":
                        break
                    j += 1
            out.append(text[i:j + 1] if keep_strings else '"' + blank(text[i + 1:j]) + '"')
            i = j + 1
            continue
        if c == "'":
            m = re.match(r"'(?:\\.[^']*|[^'\\])'", text[i:i + 12])
            if m:
                out.append(m.group(0) if keep_strings else "'" + " " * (len(m.group(0)) - 2) + "'")
                i += len(m.group(0))
                continue
        out.append(c)
        i += 1
    return "".join(out)


def line_starts(text):
    starts = [0]
    for m in re.finditer(r"\n", text):
        starts.append(m.end())
    return starts


def line_no(starts, pos):
    lo, hi = 0, len(starts) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if starts[mid] <= pos:
            lo = mid
        else:
            hi = mid - 1
    return lo


def summary_above(lines, line):
    """First sentence of the <summary> in the /// block directly above 0-based `line` (attribute lines may sit between)."""
    k = line - 1
    doc = []
    while k >= 0:
        s = lines[k].strip()
        if s.startswith("///"):
            doc.insert(0, s[3:])
        elif s.startswith("[") and s.endswith("]"):
            pass
        else:
            break
        k -= 1
    blob = " ".join(doc)
    if not blob:
        return ""
    if re.search(r"<inheritdoc", blob):
        return "Inherited documentation."
    m = re.search(r"<summary>(.*?)</summary>", blob, re.S)
    if not m:
        return ""
    txt = re.sub(r"<see\s+cref=\"([^\"]+)\"\s*/>", lambda mm: mm.group(1).split(".")[-1], m.group(1))
    txt = re.sub(r"<(?:param|typeparam)ref\s+name=\"([^\"]+)\"\s*/>", r"\1", txt)
    txt = re.sub(r"</?[a-zA-Z][^>]*>", "", txt)
    txt = " ".join(html.unescape(txt).split())
    first = re.match(r"(.+?[.!?])(?:\s|$)", txt)
    return (first.group(1) if first else txt).strip()


# ---------------------------------------------------------------------------------------------------------------
# the scanner

class TypeInfo:
    def __init__(self, ns, name, kind, header, summary, assembly):
        self.ns, self.name, self.kind = ns, name, kind
        self.header, self.summary, self.assembly = header, summary, assembly
        self.members = []       # (signature, summary)
        self.values = []        # enum members


def strip_attributes(h):
    h = h.lstrip()
    while h.startswith("["):
        depth, i = 0, 0
        while i < len(h):
            if h[i] == "[":
                depth += 1
            elif h[i] == "]":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        h = h[i + 1:].lstrip()
    return h


def norm(h):
    return " ".join(h.split())


def matching_brace(code, i):
    depth = 0
    while i < len(code):
        if code[i] == "{":
            depth += 1
        elif code[i] == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(code) - 1


def read_chunk(code, i):
    """From i: the header up to the first ';' or '{' at bracket depth 0. Returns (header, terminator, expr, end_index);
    `expr` is '=>' or '=' when an initializer or expression body was skipped to its ';'."""
    n = len(code)
    depth = 0
    j = i
    while j < n:
        c = code[j]
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        elif depth == 0 and c == ";":
            return code[i:j], ";", None, j + 1
        elif depth == 0 and c == "{":
            return code[i:j], "{", None, j
        elif depth == 0 and c == "}":
            return code[i:j], "}", None, j
        elif depth == 0 and c == "=":
            nxt = code[j + 1] if j + 1 < n else ""
            prev = code[j - 1] if j > 0 else " "
            if nxt == ">":
                k = skip_expression(code, j + 2)
                return code[i:j], ";", "=>", k
            if nxt == "=" or prev in "=!<>":
                j += 1 if nxt == "=" else 0
            else:
                k = skip_expression(code, j + 1)
                return code[i:j], ";", "=", k
        j += 1
    return code[i:], "}", None, n


def skip_expression(code, j):
    """Index just past the ';' ending an expression that started at j (all brackets and braces balanced)."""
    depth, n = 0, len(code)
    while j < n:
        c = code[j]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth < 0:
                return j
        elif c == ";" and depth == 0:
            return j + 1
        j += 1
    return n


def accessors(body):
    got = []
    for kw in ("get", "set", "init"):
        for m in re.finditer(r"(\b(?:private|internal|protected)\s+(?:internal\s+)?)?\b%s\b" % kw, body):
            if not m.group(1):
                got.append(kw)
                break
    return got


def scan_file(path, assembly, types):
    raw = read(path)
    code = code_view(raw)
    tview = code_view(raw, keep_strings=True)         # the same offsets with string literals intact, for the signatures
    lines = raw.split("\n")
    starts = line_starts(raw)
    scopes = [("file", "", True, None)]       # (kind, name, public, TypeInfo)
    ns_file = ""
    i, n = 0, len(code)

    def current_ns():
        parts = [s[1] for s in scopes if s[0] == "ns" and s[1]]
        return ".".join(([ns_file] if ns_file else []) + parts)

    def type_chain():
        return [s[1] for s in scopes if s[0] == "type"]

    while i < n:
        while i < n and code[i].isspace():
            i += 1
        if i >= n:
            break
        if code[i] == "}":
            if len(scopes) > 1:
                scopes.pop()
            i += 1
            continue
        start = i
        header, term, expr, end = read_chunk(code, i)
        i = end
        h = norm(strip_attributes(header))
        ht = norm(strip_attributes(tview[start:start + len(header)]))
        ln = line_no(starts, start)
        if term == "}":
            continue                          # a header cut by '}': the brace is handled on the next pass
        if h.startswith("="):
            continue
        top = scopes[-1]
        if re.match(r"(global\s+)?using\b", h) or re.match(r"extern\s+alias\b", h):
            continue
        m = re.match(r"namespace\s+([\w.]+)$", h)
        if m:
            if term == ";":
                ns_file = m.group(1)
            else:
                scopes.append(("ns", m.group(1), True, None))
            continue
        if top[0] not in ("file", "ns", "type"):
            if term == "{":
                i = matching_brace(code, end) + 1
            continue
        pub_mod = re.search(r"\bpublic\b", h) is not None
        info_top = top[3]
        in_iface = top[0] == "type" and info_top is not None and info_top.kind == "interface"
        tm = TYPE_DECL.match(h)
        if tm:
            kind, name = tm.group(1).split()[0], tm.group(2)
            visible = top[2] and (pub_mod or in_iface)
            info = None
            if visible:
                full = ".".join(type_chain() + [name])
                key = (assembly, current_ns(), full)
                clean = norm(re.sub(r"\bpartial\b\s*", "", ht))
                info = types.get(key)
                if info is None:
                    info = TypeInfo(current_ns(), full, kind, clean, summary_above(lines, ln), assembly)
                    types[key] = info
                else:
                    if len(clean) > len(info.header):
                        info.header = clean
                    if not info.summary:
                        info.summary = summary_above(lines, ln)
            if term == "{":
                if kind == "enum":
                    close = matching_brace(code, end)
                    if info is not None:
                        for part in split_commas(code[end + 1:close]):
                            em = re.match(r"([A-Za-z_]\w*)\s*(?:=\s*(.+))?$", norm(strip_attributes(part.strip())), re.S)
                            if em:
                                info.values.append(em.group(1) + (" = " + norm(em.group(2)) if em.group(2) else ""))
                    i = close + 1
                else:
                    scopes.append(("type", name, bool(visible), info))
                    i = end + 1
            continue
        is_pub = pub_mod or in_iface
        if re.match(r"(?:\w+\s+)*delegate\b", h):
            name = re.search(r"([A-Za-z_]\w*)\s*(?:<[^>]*>)?$", h.split("(")[0])
            if top[2] and pub_mod and name:
                if top[0] == "type" and info_top is not None:
                    info_top.members.append((norm_sig(ht), summary_above(lines, ln)))
                elif top[0] != "type":
                    types.setdefault((assembly, current_ns(), name.group(1)),
                                     TypeInfo(current_ns(), name.group(1), "delegate", norm_sig(ht),
                                              summary_above(lines, ln), assembly))
            continue
        if top[0] != "type":
            if term == "{":                    # a statement or body outside any type: nothing to index
                i = matching_brace(code, end) + 1
            continue
        if term == "{":
            close = matching_brace(code, end)
            body = code[end:close + 1]
            i = close + 1
            if top[2] and is_pub and info_top is not None and h:
                sig = norm_sig(ht)
                if "(" not in sig:
                    acc = accessors(body)
                    if acc:
                        sig += " { " + "; ".join(acc) + "; }"
                info_top.members.append((sig, summary_above(lines, ln)))
            continue
        if term == ";" and top[2] and is_pub and info_top is not None and h:
            sig = norm_sig(ht)
            if expr == "=>" and "(" not in sig:
                sig += " { get; }"
            if expr == "=" and re.search(r"\bconst\b", sig):
                val = norm(tview[start:end].split("=", 1)[1].rstrip("; \n"))
                if val and len(val) <= 40:
                    sig += " = " + val
            info_top.members.append((sig, summary_above(lines, ln)))


def norm_sig(h):
    h = re.sub(r"\)\s*:\s*(base|this)\s*\(.*$", ")", h)
    return norm(h)


def split_commas(s):
    parts, depth, cur = [], 0, []
    for ch in s:
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur))
    return parts


# ---------------------------------------------------------------------------------------------------------------
# pages

def assembly_dir(assembly):
    return os.path.join(EXTERNAL_ROOTS.get(assembly, CSHARP), assembly)


def source_files(assembly):
    root = assembly_dir(assembly)
    out = []
    for dp, dn, fn in os.walk(root):
        dn[:] = sorted(d for d in dn if d not in ("bin", "obj"))
        for f in sorted(fn):
            if f.endswith(".cs"):
                out.append(os.path.join(dp, f))
    return out


def esc(s):
    return s.replace("<", "&lt;").replace(">", "&gt;")


def assembly_page(assembly):
    types = {}
    files = source_files(assembly)
    for f in files:
        scan_file(f, assembly, types)
    ordered = sorted(types.values(), key=lambda t: (t.ns, t.name.lower(), t.name))
    members = sum(len(t.members) + len(t.values) for t in ordered)
    out = [MARK, "", "# %s public API" % assembly, "",
           "%d public types and %d public members, read from `%s/` (%d source files). "
           "Signatures are single lines as declared; the sentence after each is the first line of its XML summary." % (
               len(ordered), members, rel(assembly_dir(assembly)), len(files)), ""]
    ns = None
    for t in ordered:
        if t.ns != ns:
            ns = t.ns
            out += ["## namespace %s" % (ns or "(global)"), ""]
        out.append("### %s" % esc(t.name))
        out.append("")
        out.append("`%s`" % t.header + (" - " + esc(t.summary) if t.summary else ""))
        out.append("")
        if t.values:
            out.append("Values: " + ", ".join("`%s`" % v for v in t.values))
            out.append("")
        for sig, summ in t.members:
            out.append("- `%s`%s" % (sig, " - " + esc(summ) if summ else ""))
        if t.members:
            out.append("")
    return "\n".join(out), len(ordered), members


def build_pages():
    pages = {}
    stats = []
    for a in ASSEMBLIES:
        if not os.path.isdir(assembly_dir(a)):
            continue
        text, nt, nm = assembly_page(a)
        pages[a + ".md"] = text
        stats.append((a, nt, nm))
    idx = [MARK, "", "# C# API index", "",
           "Generated from source by `scripts/csharp-api-index.py`. Hand-written guides: `docs/SCRIPTING_API.md`, "
           "`docs/SCRIPTING.md`. Every Aver Node is a thin wrapper over a member listed here (`docs/nodes/`).", "",
           "| Assembly | Public types | Public members |", "|---|---|---|"]
    for a, nt, nm in stats:
        idx.append("| [%s](%s.md) | %d | %d |" % (a, a, nt, nm))
    idx.append("")
    pages["index.md"] = "\n".join(idx)
    return pages


def existing(dirpath):
    out = {}
    if os.path.isdir(dirpath):
        for f in os.listdir(dirpath):
            if f.endswith(".md"):
                out[f] = read(os.path.join(dirpath, f))
    return out


def main():
    ap = argparse.ArgumentParser(description="Index the public C# scripting surface into docs/api.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a page is missing or stale")
    ap.add_argument("--write", action="store_true", help="regenerate docs/api")
    ap.add_argument("--out", metavar="DIR", help="write the pages here instead of docs/api (for a trial run)")
    args = ap.parse_args()
    if not (args.check or args.write):
        ap.print_help()
        return 0

    pages = build_pages()
    if args.write:
        out = os.path.abspath(args.out) if args.out else DOCS_API
        os.makedirs(out, exist_ok=True)
        for name, text in pages.items():
            with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
        for name, text in existing(out).items():
            if name not in pages and text.startswith(MARK):
                os.remove(os.path.join(out, name))
                print("removed stale %s" % name)
        print("wrote %d pages to %s" % (len(pages), out))
        return 0

    have = existing(DOCS_API)
    problems = []
    for name, text in sorted(pages.items()):
        if name not in have:
            problems.append("docs/api/%s is missing" % name)
        elif have[name] != text:
            problems.append("docs/api/%s is stale" % name)
    for name, text in have.items():
        if name not in pages and text.startswith(MARK):
            problems.append("docs/api/%s is generated but no assembly produces it any more: remove it" % name)
    for p in problems:
        print("FAIL: " + p)
    if problems:
        print("\n%d problem(s). Run: python scripts/csharp-api-index.py --write" % len(problems))
        return 1
    print("C# API index ok: %d pages" % len(pages))
    return 0


if __name__ == "__main__":
    sys.exit(main())
