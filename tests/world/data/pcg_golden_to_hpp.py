# Turns the output of pcg_golden.fsx into PcgGolden.hpp.  usage: python pcg_golden_to_hpp.py golden.txt PcgGolden.hpp
import sys

def fl(s):
    if "E" in s:
        return s.replace("E", "e") + "f"
    return s + ("f" if "." in s else ".0f")

rows = [l.split() for l in open(sys.argv[1]) if not l.startswith("//") and l.strip()]
out = ["// GENERATED by tests/world/data/pcg_golden.fsx from scripting/fsharp/Aver.Pcg. Do not edit by hand.\n"
       "#pragma once\n#include <cstdint>\nnamespace pcggolden {\n"]

def tab(name, typ, items):
    out.append(f"static const {typ} {name}[] = {{\n" + "".join("    " + r + ",\n" for r in items) + "};\n")

pl = "struct { float x, y, z, qz, qw, s; int asset; }"
sc = lambda tag: [f"{{{fl(r[1])}, {fl(r[2])}, {fl(r[3])}, {fl(r[4])}, {fl(r[5])}, {fl(r[6])}, {ord(r[7]) - ord('a')}}}" for r in rows if r[0] == tag]
tab("kHash", "struct { uint32_t x, h; }", [f"{{{r[1]}u, {r[2]}u}}" for r in rows if r[0] == "H"])
tab("kHash2", "struct { int32_t s, i; uint32_t h; }", [f"{{{r[1]}, {r[2]}, {r[3]}u}}" for r in rows if r[0] == "H2"])
tab("kHash3", "struct { int32_t s, x, y, z; uint32_t h; }", [f"{{{r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]}u}}" for r in rows if r[0] == "H3"])
tab("kFloat01", "struct { uint32_t h; float v; }", [f"{{{r[1]}u, {fl(r[2])}}}" for r in rows if r[0] == "F"])
out.append("static const float kRange_9_4_m10_10 = %s;\n" % fl([r for r in rows if r[0] == "R"][0][5]))
tab("kScatterFree", pl, sc("S"))
tab("kScatterSpaced", pl, sc("T"))
tab("kInfinite", "struct { float x, y, z, v; }", [f"{{{fl(r[1])}, {fl(r[2])}, {fl(r[3])}, {fl(r[4])}}}" for r in rows if r[0] == "I"])
out.append("}\n")
open(sys.argv[2], "w").write("".join(out))
